"""Generate checked ranges for English common, optional voice and legacy OBBs."""
import argparse
import json
import struct
from pathlib import Path
import zlib
import zipfile
from cache_fat32 import Fat32
from cache_russian_details import boxes


def movie_duration_ms(read_at, size):
    moovs = [(offset, count) for kind, offset, count in boxes(read_at, size) if kind == "moov"]
    if len(moovs) != 1 or moovs[0][1] > 1 << 20:
        raise ValueError("MP4 must contain one bounded moov")
    offset, count = moovs[0]
    moov = read_at(offset, count)
    headers = [moov[offset:offset + count] for kind, offset, count in
               boxes(lambda a, n: moov[a:a + n], len(moov)) if kind == "mvhd"]
    if len(headers) != 1:
        raise ValueError("MP4 must contain one movie header")
    header = headers[0]
    if len(header) >= 20 and header[0] == 0:
        timescale, duration = struct.unpack_from(">II", header, 12)
        unknown = 0xFFFFFFFF
    elif len(header) >= 32 and header[0] == 1:
        timescale, duration = struct.unpack_from(">IQ", header, 20)
        unknown = 0xFFFFFFFFFFFFFFFF
    else:
        raise ValueError("MP4 movie header version or length invalid")
    if not timescale or not duration or duration == unknown:
        raise ValueError("MP4 movie duration invalid")
    milliseconds = (duration * 1000 + timescale - 1) // timescale
    if milliseconds > 0x7FFFFFFF:
        raise ValueError("MP4 movie duration out of range")
    return milliseconds


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("root")
    args = p.parse_args()
    root = Path(args.root).resolve()
    out = root / "work/arm32_cache"
    out.mkdir(parents=True, exist_ok=True)
    files = ["app/splits/obb_main/assets/obb/main_en.obb",
             "app/splits/obb_patch/assets/obb/patch_en.obb",
             "app/splits/rus_text/assets/obb/rus_text.obb", "app/splits/rus_voice/assets/obb/rus_voice.obb"]
    files += [f"app/splits/{language}_voice/assets/obb/{language}_voice.obb"
              for language in ("de", "es", "fr", "it", "pt")]
    # These immutable source containers remain a separate, complete external pair.
    files += ["com.doublefine.grimfandangoremastered/main.150.com.doublefine.grimfandangoremastered.obb",
              "com.doublefine.grimfandangoremastered/patch.1512.com.doublefine.grimfandangoremastered.obb"]
    checks, sources, entries = [], [], []
    for source_id, filename in enumerate(files):
        fs = Fat32(root / filename)
        start = len(checks)
        ranges = [{"offset": 0, "length": fs.data_offset}]
        ranges += [span for spans in fs.directories.values() for span in spans]
        ranges.append({"offset": fs.volume_size, "length": len(fs.footer)})
        for r in ranges:
            checks.append({**r, "crc32": zlib.crc32(fs.read_at(r["offset"], r["length"]))})
        sources.append({"asset": "obb/" + Path(filename).name, "external": Path(filename).name,
                        "size": fs.path.stat().st_size, "check_first": start, "check_count": len(checks) - start})
        for name, entry in fs.entries.items():
            spans = fs.extents(name)
            if len(spans) != 1:
                raise ValueError(f"{filename}:{name} is fragmented; rebuild/select a different reader")
            assert spans[0]["length"] == entry["size"]
            entries.append({"path": name.lower(), "source": source_id,
                            "offset": spans[0]["offset"], "size": entry["size"],
                            "video_duration_ms": movie_duration_ms(lambda a, n: fs.read(entry, a, n), entry["size"]) if name.lower().endswith(".mp4") else 0})
        fs.fp.close()
    with zipfile.ZipFile(root / "GrimFandango_GOG.apk") as apk:
        base = sorted(i.filename[7:] for i in apk.infolist() if i.filename.startswith("assets/") and not i.is_dir())
    lines = ["/* Generated by work/tools/cache_runtime_index.py; do not edit. */",
             "#define CACHE_ORIGINAL_MAIN 9U",
             "#define CACHE_ORIGINAL_PATCH 10U",
             "static const int cache_voice_sources[] = {-1,4,5,6,7,8};",
             "typedef struct { uint64_t offset, length; uint32_t crc; } CacheCheck;",
             "typedef struct { const char *asset, *external; uint64_t size; unsigned first, count; } CacheSpec;",
             "typedef struct { const char *name; unsigned source; uint64_t offset, size; uint32_t video_duration_ms; } CacheEntry;",
             "static const CacheCheck cache_checks[] = {"]
    lines += [f"  {{{c['offset']}ULL,{c['length']}ULL,0x{c['crc32']:08x}U}}," for c in checks]
    lines += ["};", "static const CacheSpec cache_specs[] = {"]
    lines += ["  {" + json.dumps(s["asset"]) + "," + json.dumps(s["external"]) + f",{s['size']}ULL,{s['check_first']},{s['check_count']}}}," for s in sources]
    lines += ["};", "static const CacheEntry cache_entries[] = {"]
    lines += ["  {" + json.dumps(e["path"]) + f",{e['source']},{e['offset']}ULL,{e['size']}ULL,{e['video_duration_ms']}U}}," for e in entries]
    lines += ["};", "static const char *const cache_base_assets[] = {"]
    lines += ["  " + json.dumps(n) + "," for n in base]
    lines += ["};", ""]
    (out / "cache_index.h").write_text("\n".join(lines), encoding="utf-8")
    (root / "work/cache_analysis/runtime_range_index.json").write_text(json.dumps({
        "layout": "english_common_optional_original_voices",
        "voice_languages": ["en", "de", "es", "fr", "it", "pt"],
        "voice_sources": [-1, 4, 5, 6, 7, 8], "original_external_pair": [9, 10],
        "sources": sources, "checks": checks, "entries": entries, "base_assets": base}, indent=2) + "\n", encoding="utf-8")
    print("runtime index", len(sources), "containers,", len(entries), "OBB files,", len(base), "base assets")


if __name__ == "__main__":
    main()
